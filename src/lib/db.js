import Dexie from 'dexie';
import { liveQuery } from 'dexie';
import { readable } from 'svelte/store';
import dexieCloud from 'dexie-cloud-addon';
import cloudConfig from '../../dexie-cloud.json';

/**
 * Dexie Cloud is attached as an addon so every write to a synced table is
 * queued for upload and every server change is streamed back into IndexedDB.
 *
 * `nameSuffix: false` keeps the IndexedDB name as "read-it-later" (instead of
 * appending part of the database URL). That lets databases created before the
 * cloud migration keep their data and be uploaded on first sign-in.
 *
 * `requireAuth: true` makes Dexie Cloud authenticate before any database
 * operation. The auth dialogs are rendered by Login.svelte (`customLoginGui`)
 * so the sign-in flow matches the rest of the app.
 */
export const db = new Dexie('read-it-later', { addons: [dexieCloud] });

db.version(1).stores({
  articles: '++id, status, createdAt, url',
});

// Dexie cannot change a primary key in place, so version 2 removes the old
// numeric-keyed table and copies its rows into a local-only staging table.
db.version(2)
  .stores({
    articles: null,
    legacyArticles: '++id, url, title, status, createdAt',
  })
  .upgrade(async (tx) => {
    try {
      const legacy = await tx.table('articles').toArray();
      if (legacy.length) {
        await tx.table('legacyArticles').bulkAdd(
          legacy.map(({ id, ...article }) => article)
        );
      }
    } catch (error) {
      // On a fresh install the old table does not exist.
      console.warn('Could not stage local articles for migration', error);
    }
  });

// Re-create `articles` with a Dexie Cloud primary key. `@id` lets the addon
// generate globally unique IDs after the initial sync.
db.version(3).stores({
  articles: '@id, status, createdAt, url',
});

db.cloud.configure({
  databaseUrl: import.meta.env.VITE_DEXIE_CLOUD_URL || cloudConfig.dbUrl,
  requireAuth: true,
  // We render the OTP prompt ourselves in Login.svelte so the auth UI matches
  // the rest of the app. `db.cloud.login()` still drives the built-in flow.
  customLoginGui: true,
  socialAuth: false,
  // The staging table only exists to rescue pre-cloud local data.
  unsyncedTables: ['legacyArticles'],
  // Foreground sync: the Workbox service worker generated by vite-plugin-pwa
  // does not import Dexie Cloud's service-worker module.
  tryUseServiceWorker: false,
  nameSuffix: false,
});

/** Wrap an RxJS observable in a Svelte readable store. */
function fromObservable(observable, initialValue) {
  return readable(initialValue, (set) => {
    const subscription = observable.subscribe(set);
    return () => subscription.unsubscribe();
  });
}

/** Live list of every saved article, newest first. */
export const articles = readable([], (set) => {
  const subscription = liveQuery(() =>
    db.articles.orderBy('createdAt').reverse().toArray()
  ).subscribe({
    next: set,
    error: (error) => console.error('Could not read saved articles', error),
  });

  return () => subscription.unsubscribe();
});

/** The signed-in user (or the unauthorized placeholder while loading). */
export const currentUser = fromObservable(db.cloud.currentUser, db.cloud.currentUser.value);

/** Pending login/OTP dialog emitted by Dexie Cloud's authentication flow. */
export const userInteraction = fromObservable(db.cloud.userInteraction, undefined);

/** Connection/sync progress shown while the app boots. */
export const syncState = fromObservable(db.cloud.syncState, db.cloud.syncState.value);

export async function addArticle(url) {
  return db.articles.add({
    url,
    title: '',
    status: 'unread',
    createdAt: Date.now(),
  });
}

export async function setArticleStatus(id, status) {
  return db.articles.update(id, { status });
}

export async function deleteArticle(id) {
  return db.articles.delete(id);
}

/**
 * Pull everything from the cloud before the first render so the list is
 * complete. Called once per signed-in session by App.svelte.
 */
export async function pullFromCloud() {
  await db.cloud.sync({ purpose: 'pull', wait: true });
}

/**
 * Move articles saved before the cloud migration into the synced table.
 * Runs after the first pull so Dexie Cloud knows the ID prefix to generate.
 */
export async function migrateLegacyArticles() {
  let legacy;
  try {
    legacy = await db.legacyArticles.toArray();
  } catch {
    return 0;
  }

  if (!legacy.length) return 0;

  let migrated = 0;

  for (const { id, ...article } of legacy) {
    try {
      const existing = await db.articles.where('url').equals(article.url).first();
      if (!existing) {
        await db.articles.add({
          url: article.url,
          title: article.title ?? '',
          status: article.status === 'read' ? 'read' : 'unread',
          createdAt: article.createdAt ?? Date.now(),
        });
        migrated += 1;
      }

      await db.legacyArticles.delete(id);
    } catch (error) {
      console.error('Could not migrate a locally saved article', error);
      // Keep the row in the staging table so a later sign-in can retry.
      return migrated;
    }
  }

  return migrated;
}

/** Push anything still pending, then end the session. */
export async function signOut() {
  try {
    await db.cloud.sync({ purpose: 'push', wait: true });
  } catch (error) {
    console.warn('Could not flush changes before signing out', error);
  }

  await db.cloud.logout({ force: true });
}
